#!/usr/bin/env python3
"""
4.1_build_species_dataset.py
Validate and filter the species-level dataset generated by 4.0.

This script does not perform sequence searches, classification, or representative sequence selection.
It preserves the labels and representative accessions created in 4.0 and only checks dataset integrity
before feature extraction.

Validation checks include:
- required columns are present
- dataset is not empty
- no duplicate species entries
- valid class labels
- representative accessions are unique to one species
- representative sequences exist in the validated FASTA files

Unresolved species annotations are retained for QC reporting but
removed from the final ML dataset, ensuring one biologically resolved
species per row.

Input:
- out/species_master_table.csv
- out/nirk.fasta
- out/pcuac_functional.fasta

Output:
- out/species_dataset.csv (species_resolved == 1 only, ML-ready)
- out/pipeline_metadata/4.1_build_species_dataset_metadata.txt

"""

import csv
import os
import sys
import platform
import datetime

REQUIRED_COLUMNS = [
    "species", "taxid", "organism_name", "nirK_present", "pcuac_present",
    "class", "nirK_rep_accession", "pcuac_rep_accession", "species_resolved",
]
VALID_CLASSES = {"both", "nirK_only", "pcuac_only"}

PIPELINE_VERSION = "stage4.v2"


def read_fasta_headers(path):
    """
    Lightweight FASTA header read (accessions only) to check that
    representative accessions actually exist in the validated FASTA.
    """
    if not os.path.exists(path):
        sys.exit(f"ERROR: FASTA not found: {path}")
    headers = set()
    with open(path) as fh:
        for line in fh:
            if line.startswith(">"):
                headers.add(line[1:].split()[0])
    return headers

def write_pipeline_metadata(outdir, script_name, input_files, output_files, notes=""):
    os.makedirs(outdir, exist_ok=True)
    path = os.path.join(outdir, f"{script_name}_metadata.txt")
    with open(path, "w") as fh:
        fh.write("Stage: 4\n")
        fh.write(f"Script: {script_name}\n")
        fh.write(f"Pipeline version: {PIPELINE_VERSION}\n\n")
        fh.write(f"Date generated: {datetime.datetime.now().isoformat(timespec='seconds')}\n\n")
        fh.write(f"Python: {platform.python_version()}\n\n")
        fh.write("Input files:\n")
        for f in input_files:
            fh.write(f"- {f}\n")
        fh.write("\nOutput files:\n")
        for f in output_files:
            fh.write(f"- {f}\n")
        if notes:
            fh.write("\n" + notes.strip() + "\n")
    print(f"wrote {path}")

def main():
    input_file = "out/species_master_table.csv"
    nirK_fasta = "out/nirk.fasta"
    pcuac_fasta = "out/pcuac_functional.fasta"
    output_file = "out/species_dataset.csv"

    if not os.path.exists(input_file):
        sys.exit(f"ERROR: input file not found: {input_file}")

    with open(input_file, newline="") as fh:
        reader = csv.DictReader(fh)
        rows = list(reader)
        fieldnames = reader.fieldnames or []

    if not rows:
        sys.exit(f"ERROR: {input_file} is empty.")

    missing_cols = [c for c in REQUIRED_COLUMNS if c not in fieldnames]
    if missing_cols:
        sys.exit(f"ERROR: {input_file} missing required column(s): {missing_cols}")

    species_seen = [r["species"] for r in rows]
    dupes = sorted({s for s in species_seen if species_seen.count(s) > 1})
    if dupes:
        sys.exit(f"ERROR: duplicate species row(s) in {input_file}: {dupes}")

    bad_classes = sorted({r["class"] for r in rows if r["class"] not in VALID_CLASSES})
    if bad_classes:
        sys.exit(f"ERROR: invalid class label(s) found: {bad_classes}")

    nirK_reps = [r["nirK_rep_accession"] for r in rows if r["nirK_rep_accession"] not in ("NA", "")]
    pcuac_reps = [r["pcuac_rep_accession"] for r in rows if r["pcuac_rep_accession"] not in ("NA", "")]

    dup_nirK = sorted({a for a in nirK_reps if nirK_reps.count(a) > 1})
    dup_pcuac = sorted({a for a in pcuac_reps if pcuac_reps.count(a) > 1})
    if dup_nirK:
        sys.exit(f"ERROR: NirK representative accession used for more than one species: {dup_nirK}")
    if dup_pcuac:
        sys.exit(f"ERROR: PCuAC representative accession used for more than one species: {dup_pcuac}")

    nirK_headers = read_fasta_headers(nirK_fasta)
    pcuac_headers = read_fasta_headers(pcuac_fasta)

    missing_nirK = [a for a in nirK_reps if a not in nirK_headers]
    missing_pcuac = [a for a in pcuac_reps if a not in pcuac_headers]
    if missing_nirK:
        sys.exit(f"ERROR: NirK representative accession(s) not found in {nirK_fasta}: {missing_nirK}")
    if missing_pcuac:
        sys.exit(f"ERROR: PCuAC representative accession(s) not found in {pcuac_fasta}: {missing_pcuac}")

    print("-" * 50)
    print("Species master table validated")
    print(f"Species rows (QC, all): {len(rows)}")

    resolved_rows = [r for r in rows if r["species_resolved"] == "1"]
    unresolved_rows = [r for r in rows if r["species_resolved"] != "1"]

    print(f"Resolved (kept for ML): {len(resolved_rows)}")
    print(f"Unresolved (excluded, QC only): {len(unresolved_rows)}")
    if not resolved_rows:
        sys.exit("ERROR: no species_resolved==1 rows remain; final ML dataset would be empty.")

    with open(output_file, "w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(resolved_rows)

    print(f"wrote {output_file}")
    print("-" * 50)

    write_pipeline_metadata(
        outdir="out/pipeline_metadata",
        script_name="4.1_build_species_dataset",
        input_files=[input_file, nirK_fasta, pcuac_fasta],
        output_files=[output_file],
        notes=(
            "Representative selection rule: longest validated sequence per species\n"
            "Filtering rule: species_resolved == 1 required for ML dataset"
        ),
    )

if __name__ == "__main__":
    main()